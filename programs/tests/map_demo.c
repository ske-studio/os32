/* ====================================================================== */
/*  スキャンコード定数                                                     */
/* ====================================================================== */

#define SC_ESC    0x00
#define SC_W      0x11
#define SC_A      0x1D
#define SC_S      0x1F
#define SC_D      0x20
#define SC_SPACE  0x34
#define SC_UP     0x3A
#define SC_LEFT   0x3B
#define SC_RIGHT  0x3C
#define SC_DOWN   0x3D

/* ====================================================================== */
/*  キー入力 (トリガー検出)                                                */
/* ====================================================================== */

#define NUM_KEYS 9
static const int g_sclist[NUM_KEYS] = {
    SC_ESC, SC_W, SC_A, SC_S, SC_D,
    SC_SPACE, SC_UP, SC_LEFT, SC_RIGHT
};
/* SC_DOWN は SC_S と同じ方向なので省略、代わりに SC_RIGHT を使う */

static int g_cur[NUM_KEYS];
static int g_prev[NUM_KEYS];

#define KI_ESC   0
#define KI_W     1
#define KI_A     2
#define KI_S     3
#define KI_D     4
#define KI_SPACE 5
#define KI_UP    6
#define KI_LEFT  7
#define KI_RIGHT 8

static void keys_poll(void)
{
    int i;
    for (i = 0; i < NUM_KEYS; i++)
        g_cur[i] = api->kbd_is_pressed(g_sclist[i]);
}

static int key_trigger(int idx)
{
    return g_cur[idx] && !g_prev[idx];
}

static void keys_save(void)
{
    int i;
    for (i = 0; i < NUM_KEYS; i++)
        g_prev[i] = g_cur[i];
}

/* ====================================================================== */
/*  HUD描画 (グラフィックVRAMに直接描画)                                   */
/* ====================================================================== */

/* タイルマップ描画領域の下にHUDを配置 */
/* tilemap_set_origin で (8,8) にすると、384x384 + 8 = 392 → HUD Y=393 */
#define HUD_X   8
#define HUD_Y   390

static void draw_hud(const MapDef *m, i16 cx, i16 cy)
{
    /* HUD領域をクリア */
    gfx_fill_rect(0, HUD_Y - 2, 640, 12, 0);

    gfx_printf(HUD_X, HUD_Y, 7,
        "Map:%d [%s] %dx%d  Cam:(%d,%d)",
        (int)m->id, m->name, (int)m->width, (int)m->height,
        (int)cx, (int)cy);

    gfx_puts(400, HUD_Y, "WASD:Move Space:Warp ESC:Quit", 5);
}

/* ====================================================================== */
/*  メイン                                                                  */
/* ====================================================================== */

void main(int argc, char **argv, KernelAPI *k)
{
    int rc;
    const MapDef *m;
    i16 cam_x, cam_y;
    u32 last_tick;
    int need_redraw;

    (void)argc; (void)argv; (void)k;

    api->kprintf(ATTR_WHITE, "map_demo: initializing...\n");

    /* --- libtilemap 初期化 (内部でGFXも初期化) --- */
    tilemap_init(api);
    gfx_clear(0);
    gfx_present();

    /* --- タイル定義 (埋め込みデータ, ID = DB の tile_id と一致) --- */
    tilemap_define(0, tile_grass);
    tilemap_define(1, tile_wall);
    tilemap_define(2, tile_water);
    tilemap_define(3, tile_tree);
    tilemap_define(4, tile_ice);
    tilemap_define(5, tile_swamp);
    tilemap_define(6, tile_warp);
    tilemap_define(7, tile_save);

    /* --- libos32map 初期化 --- */
    rc = map_init("/db/map.db");
    if (rc < 0) {
        api->kprintf(ATTR_RED, "map_init failed: %d\n", rc);
        tilemap_shutdown();
        return;
    }

    /* --- マップ1 ロード --- */
    rc = map_load(1);
    if (rc < 0) {
        api->kprintf(ATTR_RED, "map_load(1) failed: %d\n", rc);
        map_shutdown();
        tilemap_shutdown();
        return;
    }

    /* カメラ初期位置 (マップ中央) */
    m = map_current();
    cam_x = (i16)(m->width / 2);
    cam_y = (i16)(m->height / 2);
    map_set_camera(cam_x, cam_y);

    /* BG0 に地面レイヤーを転送 */
    tilemap_set_visible(0, 1);
    map_apply_to_tilemap(0, 0);

    /* 初期描画 */
    tilemap_force_redraw();
    tilemap_compose_btf();
    draw_hud(m, cam_x, cam_y);
    tilemap_present();

    last_tick = api->get_tick();

    /* ====== メインループ ====== */
    while (1) {
        need_redraw = 0;

        keys_poll();

        /* ESC: 終了 */
        if (g_cur[KI_ESC]) break;

        /* WASD / 矢印キー: カメラ移動 */
        if (key_trigger(KI_W) && cam_y > 0)                { cam_y--; need_redraw = 1; }
        if (key_trigger(KI_S) && cam_y < (i16)m->height-1) { cam_y++; need_redraw = 1; }
        if (key_trigger(KI_A) && cam_x > 0)                { cam_x--; need_redraw = 1; }
        if (key_trigger(KI_D) && cam_x < (i16)m->width-1)  { cam_x++; need_redraw = 1; }

        /* Space: マップ切替 */
        if (key_trigger(KI_SPACE)) {
            u16 cur_id = m->id;
            u16 next_id = (cur_id == 1) ? 2 : 1;

            rc = map_load(next_id);
            if (rc == 0) {
                m = map_current();
                cam_x = (i16)(m->width / 2);
                cam_y = (i16)(m->height / 2);
                need_redraw = 1;
            }
        }

        keys_save();

        /* --- 描画 --- */
        if (need_redraw) {
            map_set_camera(cam_x, cam_y);
            map_apply_to_tilemap(0, 0);

            tilemap_force_redraw();
            tilemap_compose_btf();
            draw_hud(m, cam_x, cam_y);
            tilemap_present();
        }

        /* フレーム待ち (~30fps, 3tick = 30ms) */
        while (api->get_tick() - last_tick < 3) {
            api->sys_halt();
        }
        last_tick = api->get_tick();
    }

    map_shutdown();
    tilemap_shutdown();
}

