/* ======================================================================== */
/*  LIBOS32MAP.H — OS32 マップ管理ライブラリ 公開ヘッダ                      */
/*                                                                          */
/*  RPG/アクション向けマップデータ管理ライブラリ。                            */
/*  マップ構造・タイルセット定義・イベント配置・ワープ・エンカウント設定を     */
/*  SQLiteデータベースで一元管理し、ランタイムではRAMキャッシュで高速動作。    */
/*                                                                          */
/*  依存: libos32db (KAPI経由SQLite)                                        */
/*  描画 (libtilemap / libos32gfx) には依存しない。                          */
/* ======================================================================== */

#ifndef LIBOS32MAP_H
#define LIBOS32MAP_H

#include "os32_kapi_shared.h"    /* u8, u16, u32, i8, i16, i32 */

/* ====================================================================== */
/*  1. マップサイズ制約                                                    */
/* ====================================================================== */

/* 幅・高さは 8 の倍数 (8, 16, 24, ..., 248) */
/* 8の倍数制約理由: PC-98のVRAMバイト境界 + タイルアライメント最適化 */
#define MAP_ALIGN       8       /* サイズアライメント (8の倍数) */
#define MAP_MIN_SIZE    8       /* 最小マップサイズ (8x8) */
#define MAP_MAX_SIZE    248     /* 最大マップサイズ (248x248, メモリ上限) */
#define MAP_MAX_LAYERS  3       /* レイヤー上限 (地面/装飾/前景) */

/* サイズバリデーション */
#define MAP_SIZE_VALID(n) \
    ((n) >= MAP_MIN_SIZE && (n) <= MAP_MAX_SIZE && ((n) % MAP_ALIGN) == 0)

/* ====================================================================== */
/*  2. 配列上限                                                            */
/* ====================================================================== */

#define MAP_MAX_TILE_PROPS  256  /* タイルプロパティ上限 */
#define MAP_MAX_EVENTS       64  /* イベント上限 */
#define MAP_MAX_WARPS        32  /* ワープ上限 */
#define MAP_MAX_ENCOUNTERS   16  /* エンカウント上限 */

/* ====================================================================== */
/*  3. タイルフラグ                                                        */
/* ====================================================================== */

#define MAP_TFLAG_NONE       0x00
#define MAP_TFLAG_ENCOUNTER  0x01  /* エンカウント判定あり */
#define MAP_TFLAG_SLIPPERY   0x02  /* 氷床 (移動慣性) */
#define MAP_TFLAG_SLOW       0x04  /* 沼 (移動速度低下) */
#define MAP_TFLAG_WARP       0x08  /* ワープポイント */
#define MAP_TFLAG_EVENT      0x10  /* イベントトリガー */
#define MAP_TFLAG_SAVE       0x20  /* セーブポイント */

/* ====================================================================== */
/*  4. トリガー種別                                                        */
/* ====================================================================== */

#define MAP_TRIG_STEP       0   /* 踏んだ時 */
#define MAP_TRIG_ACTION     1   /* 調べた時 (Aボタン) */
#define MAP_TRIG_AUTO       2   /* 画面に入った時 */
#define MAP_TRIG_TOUCH      3   /* 接触時 */

/* ====================================================================== */
/*  5. イベント種別                                                        */
/* ====================================================================== */

#define MAP_EVT_NONE        0
#define MAP_EVT_WARP        1   /* ワープ (param=dest_map_id) */
#define MAP_EVT_MESSAGE     2   /* メッセージ表示 */
#define MAP_EVT_TREASURE    3   /* 宝箱 */
#define MAP_EVT_NPC         4   /* NPC会話 */
#define MAP_EVT_BATTLE      5   /* 強制バトル */
#define MAP_EVT_SCRIPT      6   /* スクリプト実行 */

/* ====================================================================== */
/*  6. データ構造体                                                        */
/* ====================================================================== */

/* マップ定義 */
typedef struct {
    u16  id;                /* マップID (0=未使用) */
    u16  width;             /* タイル幅 (8の倍数) */
    u16  height;            /* タイル高 (8の倍数) */
    u8   layer_count;       /* 実レイヤー数 (1-3) */
    u8   tileset_id;        /* 使用タイルセットID */
    u16  bgm_id;            /* BGM番号 (0=なし) */
    u16  _pad;
    char name[16];          /* マップ名 (デバッグ用) */
} MapDef;

/* タイルプロパティ (RAMキャッシュ) */
typedef struct {
    u16  tile_id;           /* タイルID (tileset内) */
    u8   passable;          /* 通行可能 (0=壁, 1=通行可, 2=水上のみ等) */
    u8   flags;             /* MAP_TFLAG_* */
    u32  chem_elements;     /* 化学属性 (ELEM_* ビットマスク) */
    i16  chem_temperature;  /* 初期温度 (化学エンジン連携用) */
    u16  damage;            /* 接触ダメージ (0=なし) */
} TileProp;

/* マップイベント */
typedef struct {
    u16  id;                /* イベントID */
    u16  map_id;            /* 所属マップID */
    i16  x, y;              /* タイル座標 */
    u8   trigger;           /* MAP_TRIG_* */
    u8   type;              /* MAP_EVT_* */
    u16  param;             /* イベント固有パラメータ */
    char script[32];        /* スクリプト名/メッセージキー */
} MapEvent;

/* ワープ定義 */
typedef struct {
    u16  id;
    u16  src_map;           /* 出発マップID */
    i16  src_x, src_y;      /* 出発座標 */
    u16  dst_map;           /* 到着マップID */
    i16  dst_x, dst_y;      /* 到着座標 */
    u8   direction;         /* 到着時の向き (0-3) */
    u8   _pad;
} MapWarp;

/* エンカウント設定 */
typedef struct {
    u16  map_id;
    u16  enemy_id;          /* 敵グループID */
    u8   rate;              /* 出現率 (0-100) */
    u8   _pad;
    u16  min_steps;         /* 最小歩数 (出現抑制) */
} MapEncounter;

/* イベントコールバック */
typedef void (*map_event_callback)(const MapEvent *evt);

/* ====================================================================== */
/*  7. API — システム管理                                                  */
/* ====================================================================== */

/* 初期化: DBを開いてタイルプロパティをRAMにキャッシュ */
int  map_init(const char *db_path);

/* 終了: DB接続クローズ、ロード済みマップ解放 */
void map_shutdown(void);

/* ====================================================================== */
/*  8. API — マップロード・切替                                            */
/* ====================================================================== */

/* マップをDBからRAMにロード (タイルデータ + イベント + ワープ) */
/* 戻り値: 0=成功, 負=エラー */
int  map_load(u16 map_id);

/* 現在ロード済みマップを解放 */
void map_unload(void);

/* 現在のマップ定義を取得 */
const MapDef *map_current(void);

/* マップ間ワープ実行 (自動 unload→load) */
int  map_warp(u16 warp_id);

/* ====================================================================== */
/*  9. API — タイルアクセス                                                */
/* ====================================================================== */

/* 指定座標のタイル属性を取得 (libtilemap互換 u16) */
u16  map_get_tile(int layer, int col, int row);

/* タイルの通行判定 */
int  map_is_passable(int col, int row);

/* タイルのプロパティを取得 */
const TileProp *map_get_prop(int col, int row);

/* タイルの化学属性を取得 (libos32chem連携用) */
u32  map_get_chem_elements(int col, int row);

/* ====================================================================== */
/*  10. API — スクロール・ビューポート                                     */
/* ====================================================================== */

/* カメラ位置をタイル座標で設定 */
void map_set_camera(i16 tile_x, i16 tile_y);

/* カメラ位置取得 */
void map_get_camera(i16 *out_x, i16 *out_y);

/* ビューポート左上座標を取得 (カメラ位置+マップ端クランプ) */
void map_get_viewport(int *out_col, int *out_row);

/* ビューポート内のタイルを libtilemap の BG に転送 */
/* (24x24タイル分のウィンドウを切り出して tilemap_set に反映) */
/* 注: この関数を使うには libtilemap.h を事前にインクルードすること */
void map_apply_to_tilemap(int bg_layer, int map_layer);

/* ====================================================================== */
/*  11. API — イベント                                                     */
/* ====================================================================== */

/* 指定座標のイベントを検索 */
const MapEvent *map_get_event(int col, int row, u8 trigger);

/* イベントコールバック設定 */
void map_set_event_callback(map_event_callback cb);

/* 歩行時のイベント自動チェック (ワープ・エンカウント含む) */
int  map_check_step(int col, int row);

/* ====================================================================== */
/*  12. API — エンカウント                                                 */
/* ====================================================================== */

/* エンカウント判定 (歩数ベース) */
/* 戻り値: 敵グループID (0=エンカウントなし) */
u16  map_check_encounter(void);

/* 歩数カウンタリセット */
void map_reset_steps(void);

/* ====================================================================== */
/*  13. API — 化学エンジン連携                                             */
/* ====================================================================== */

/* マップタイルの化学属性を動的変更 (火で焼けた草→灰 等) */
void map_set_tile_element(int col, int row, u32 elements);

/* 指定タイルを別のタイルIDに置換 (破壊・変化演出) */
void map_replace_tile(int layer, int col, int row, u16 new_tile);

/* ====================================================================== */
/*  14. API — ユーティリティ                                               */
/* ====================================================================== */

/* 矩形範囲の通行判定 (キャラ当たり判定用) */
int  map_rect_passable(int x, int y, int w, int h);

/* デバッグ: マップ情報ダンプ */
void map_debug_dump(void);

/* ====================================================================== */
/*  15. 内部アクセサ (テストプログラム用)                                   */
/* ====================================================================== */

int  map__tile_prop_count(void);
int  map__event_count(void);
int  map__warp_count(void);
int  map__encounter_count(void);

#endif /* LIBOS32MAP_H */
