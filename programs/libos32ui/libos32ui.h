/* ======================================================================== */
/*  LIBOS32UI.H — OS32 microUI ラッパー                                     */
/*                                                                          */
/*  microui (rxi) + GFXレンダラ + 入力ブリッジの統合API                     */
/* ======================================================================== */

#ifndef LIBOS32UI_H
#define LIBOS32UI_H

#include "os32api.h"
#include "microui.h"

/* ======================================================================== */
/*  初期化・終了                                                            */
/* ======================================================================== */

/* mu_Context を初期化し、GFXレンダラと入力ブリッジを接続する。
 * ctx は呼び出し側で確保すること (巨大構造体なので static 推奨)。
 * font_w, font_h: フォントの文字幅・高さ (ピクセル)。通常 8x8。 */
void mui_init(mu_Context *ctx, KernelAPI *api, int font_w, int font_h);

/* ======================================================================== */
/*  フレーム更新                                                            */
/* ======================================================================== */

/* 入力をポーリングして mu_Context に注入する。
 * mu_begin() の前に毎フレーム呼ぶこと。 */
void mui_pump_input(mu_Context *ctx);

/* コマンドバッファを走査してGFXバックバッファに描画する。
 * mu_end() の後に呼ぶこと。 */
void mui_render(mu_Context *ctx);

/* ======================================================================== */
/*  パレット設定                                                            */
/* ======================================================================== */

/* microuiの14色スロットをPC-98パレットインデックスにマッピングする。
 * 初期化時にデフォルト設定済み。個別に変更可能。 */
void mui_set_color(mu_Context *ctx, int colorid, unsigned char pal_idx);

#endif /* LIBOS32UI_H */
