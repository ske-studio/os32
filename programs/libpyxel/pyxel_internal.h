/* ======================================================================== */
/*  PYXEL_INTERNAL.H — libpyxel 内部状態管理ヘッダ                          */
/*                                                                          */
/*  libpyxel の内部実装のみが使用する。外部プログラムからは                  */
/*  pyxel.h のみをインクルードすること。                                     */
/* ======================================================================== */

#ifndef __PYXEL_INTERNAL_H
#define __PYXEL_INTERNAL_H

#include "pyxel.h"
#include "libos32gfx.h"

/* ======================================================================== */
/*  キー状態管理定数                                                         */
/* ======================================================================== */

/* PC-98 スキャンコードの最大値 (0x00-0x7F) */
#define PYXEL_MAX_KEYS     128
/* ビットフィールドで管理 (128 / 8 = 16 バイト) */
#define PYXEL_KEY_BYTES    (PYXEL_MAX_KEYS / 8)

/* ======================================================================== */
/*  Pyxel 16色パレット → PC-98 4bit RGB 変換テーブル                        */
/*  (04_API_MAPPING.md §3-1 準拠)                                           */
/* ======================================================================== */

/* pc98_val = (pyxel_val * 15 + 127) / 255 */
static const u8 pyxel_default_palette[16][3] = {
    { 0,  0,  0},    /* 0  黒 */
    { 3,  3,  6},    /* 1  紺 */
    { 7,  2,  7},    /* 2  紫 */
    { 1,  9,  9},    /* 3  青緑 */
    { 8,  4,  5},    /* 4  茶 */
    { 3,  5,  9},    /* 5  暗青 */
    {10, 11, 15},    /* 6  薄青 */
    {14, 14, 14},    /* 7  白 */
    {12,  1,  6},    /* 8  赤 */
    {12,  8,  4},    /* 9  橙 */
    {14, 11,  5},    /* 10 黄 */
    { 7, 12, 10},    /* 11 薄緑 */
    { 7,  9, 13},    /* 12 シアン */
    {10, 10, 10},    /* 13 灰 */
    {15,  9,  9},    /* 14 ピンク */
    {14, 12, 10}     /* 15 肌色 */
};

/* ======================================================================== */
/*  内部状態構造体                                                           */
/* ======================================================================== */

typedef struct {
    /* KAPIポインタ */
    KernelAPI *kapi;

    /* 画面サイズ (pyxel_init で設定) */
    int width;
    int height;

    /* カメラオフセット (pyxel_camera で設定) */
    int cam_x;
    int cam_y;

    /* クリッピング矩形 (Pyxel座標系) */
    int clip_x;
    int clip_y;
    int clip_w;
    int clip_h;
    int clip_enabled;

    /* パレットスワップテーブル: pal_map[論理色] = 物理色 */
    u8 pal_map[PYXEL_COLORS];

    /* キー状態 (ビットフィールド) */
    u8 cur_keys[PYXEL_KEY_BYTES];
    u8 prev_keys[PYXEL_KEY_BYTES];

    /* キーホールドカウンタ (pyxel_btnp用) */
    u16 key_hold[PYXEL_MAX_KEYS];

    /* FPS計測 */
    u32 fps_tick;
    int fps_frames;
} PyxelState;

/* グローバル内部状態 (pyxel_core.c で定義) */
extern PyxelState _pyxel;

/* ======================================================================== */
/*  内部関数プロトタイプ                                                     */
/* ======================================================================== */

/* 入力状態の更新 (毎フレーム pyxel_run から呼ばれる) */
void _pyxel_update_input(void);

/* VRAM転送 (dirty rectのみ、毎フレーム pyxel_run から呼ばれる) */
void _pyxel_present(void);

/* ======================================================================== */
/*  ユーティリティマクロ                                                     */
/* ======================================================================== */

/* パレットスワップ適用 */
#define PYXEL_COL(c)  (_pyxel.pal_map[(c) & 0x0F])

/* キービット操作 */
#define PYXEL_KEY_SET(arr, k)   ((arr)[(k) >> 3] |= (1 << ((k) & 7)))
#define PYXEL_KEY_CLR(arr, k)   ((arr)[(k) >> 3] &= ~(1 << ((k) & 7)))
#define PYXEL_KEY_TST(arr, k)   ((arr)[(k) >> 3] & (1 << ((k) & 7)))

/* 座標クランプ (min, max 包含) */
#define PYXEL_CLAMP(v, lo, hi)  ((v) < (lo) ? (lo) : ((v) > (hi) ? (hi) : (v)))

/* 2値の最小/最大 */
#define PYXEL_MIN(a, b)  ((a) < (b) ? (a) : (b))
#define PYXEL_MAX(a, b)  ((a) > (b) ? (a) : (b))

#endif /* __PYXEL_INTERNAL_H */
