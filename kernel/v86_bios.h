#ifndef V86_BIOS_H
#define V86_BIOS_H

#include "types.h"
#include "v86.h"

/* INT 18h (テキスト/キーボード/グラフィックBIOS) を処理する。
 * regs: V86スタックフレーム内レジスタ配列
 * 戻り値: 1=V86終了要求, 0=処理済み(V86継続) */
int v86_bios_int18(u32 *regs);

/* INT 29h (DOS 1文字高速出力) を処理する。 */
int v86_bios_int29(u32 *regs);

/* INT 1Ch (PC-98 カレンダBIOS) を処理する。
 * regs: V86スタックフレーム内レジスタ配列
 * 戻り値: 0=処理済み, -1=未実装 */
int v86_bios_int1c(u32 *regs);

/* INT 11h (機器構成取得) を処理する。
 * 戻り値: 0=処理済み */
int v86_bios_int11(u32 *regs);

/* INT 12h (メモリサイズ取得) を処理する。
 * 戻り値: 0=処理済み */
int v86_bios_int12(u32 *regs);

#endif /* V86_BIOS_H */
