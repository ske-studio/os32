/* ======================================================================== */
/*  V86_IOCORE.H — V86 I/Oポートディスパッチテーブル                        */
/*                                                                          */
/*  NP21/W iocore.c のアーキテクチャに準拠:                                 */
/*    - 関数ポインタテーブルによる O(1) ディスパッチ                        */
/*    - 各デバイスが _bind() でポート別ハンドラを登録                       */
/*    - 16bit I/O のワードターミネート対応                                  */
/* ======================================================================== */

#ifndef V86_IOCORE_H
#define V86_IOCORE_H

#include "types.h"

/* ====================================================================== */
/*  関数ポインタ型定義                                                      */
/* ====================================================================== */
typedef u8   (*v86_inp_fn)(u16 port);
typedef void (*v86_out_fn)(u16 port, u8 val);

/* ====================================================================== */
/*  ディスパッチテーブル (port & 0xFF でインデックス)                        */
/*                                                                          */
/*  PC-98 のシステムI/O (PIC/PIT/KBD等) は10bitデコードだが、               */
/*  MS-DOS 5 の IO.SYS が使用するポートは 0x0000-0x03FF に収まるため       */
/*  port & 0xFF の 1段テーブルで実用上問題ない。                            */
/*  upper byte != 0 のアクセスはデフォルトハンドラ (実I/O直接) で処理。    */
/* ====================================================================== */
extern v86_inp_fn v86_io_inp[256];
extern v86_out_fn v86_io_out[256];

/* ====================================================================== */
/*  16bit ワードターミネートテーブル (NP21/W iocore16.tbl 準拠)             */
/*                                                                          */
/*  PC-98 独特のI/O特性: 16bit IN (INW) 時に上位バイトが不定な               */
/*  ポートがあり、正しいエミュレーションにはターミネートタイプに             */
/*  応じた処理が必要。                                                      */
/* ====================================================================== */
#define V86_TERM_NONE    0  /* 通常: port, port+1 の連続8bit読み */
#define V86_TERM_WORD    1  /* 固定値 0x2588 を返す */
#define V86_TERM_ACTIVE  2  /* 下位8bitのみ、上位はAHを維持 */
#define V86_TERM_PLUS    3  /* 下位8bitのみ、上位は0xFF */
#define V86_TERM_MINUS   4  /* 下位8bitのみ、上位は0x00 */
#define V86_TERM_EXT08   5  /* 下位8bitのみ、上位は0x08 */

#define V86_WORD_TERMINATE  0x2588

extern const u8 v86_io_terminate[256];

/* ====================================================================== */
/*  API                                                                     */
/* ====================================================================== */

/* テーブル初期化 + 全デバイスバインド */
void v86_iocore_init(void);

/* 8bit I/O (テーブルディスパッチ) */
u8   v86_iocore_inp8(u16 port);
void v86_iocore_out8(u16 port, u8 val);

/* 16bit I/O (ワードターミネート対応) */
u16  v86_iocore_inp16(u16 port, u16 cur_ax);
int  v86_iocore_out16(u16 port, u16 val);

/* リブート検知 (F0hポート) — 16bit OUTで使用 */
int  v86_iocore_is_reboot(u16 port, u8 val);

#endif /* V86_IOCORE_H */
