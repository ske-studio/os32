/* ====================================================================== */
/*  比較マスク (512バイト)                                                  */
/*  0xFF = 比較対象、0x00 = 無視 (DOS版差・時刻依存値を除外)               */
/*                                                                          */
/*  ★プレースホルダ: 全 0xFF (全バイト比較)                                */
/*  リファレンス採取後にRTC/BIOSバージョン領域を 0x00 に設定すること        */
/* ====================================================================== */
const u8 v86_dos_ref_bda_mask[512] = {
    /* デフォルト: 全バイト比較対象 */
    [0 ... 511] = 0xFF
};

/* ====================================================================== */
/*  v86_debug_compare_bda_to_ref — カーネル側 diff レポート                 */
/*                                                                          */
/*  現在のバッキングRAM上の BDA とリファレンステンプレートを比較し、         */
/*  差分をシリアルコンソールに出力する。                                     */
/* ====================================================================== */
void v86_debug_compare_bda_to_ref(void)
{
    u8 *bda;
    int i;
    int match_count = 0;
    int uninit_count = 0;
    int diff_count = 0;
    int masked_count = 0;

    bda = v86_phys_addr(0x0000, 0x0400);
    if (!paging_is_present((u32)bda)) {
        kprintf(0x0E, "[V86_REF] BDA page not present\n");
        return;
    }

    kprintf(0x0A, "[V86_REF] BDA diff vs DOS reference:\n");

    for (i = 0; i < 512; i++) {
        u8 cur = bda[i];
        u8 ref = v86_dos_ref_bda[i];
        u8 mask = v86_dos_ref_bda_mask[i];

        if (mask == 0x00) {
            masked_count++;
            continue;
        }

        if (cur == ref) {
            match_count++;
        } else if (cur == 0x00 && ref != 0x00) {
            uninit_count++;
            if (uninit_count <= 20) {
                kprintf(0x0E, "  0x%x: OS32=00 DOS=%x (uninit)\n",
                        (unsigned)(0x400 + i), (unsigned)ref);
            }
        } else {
            diff_count++;
            if (diff_count <= 20) {
                kprintf(0x0E, "  0x%x: OS32=%x DOS=%x (diff)\n",
                        (unsigned)(0x400 + i), (unsigned)cur, (unsigned)ref);
            }
        }
    }

    kprintf(0x0A, "[V86_REF] match=%d uninit=%d diff=%d masked=%d / 512\n",
            match_count, uninit_count, diff_count, masked_count);
}
