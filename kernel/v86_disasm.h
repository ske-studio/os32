/* ======================================================================== */
/*  V86_DISASM.H - V86 最小逆アセンブラ (T3.1)                              */
/*                                                                          */
/*  GPトレースの opcode バイト列を可読命令文字列に変換する。                 */
/*  完全な x86 デコーダではなく、V86 でトレース必要な命令種別のみ対応。      */
/* ======================================================================== */

#ifndef V86_DISASM_H
#define V86_DISASM_H

#include "types.h"

/* 1命令を逆アセンブルする
 * bytes: 命令バイト列の先頭ポインタ (最低16バイト有効であること)
 * out: 出力バッファ (NULLの場合は消費バイト数のみ返す)
 * outsz: outバッファサイズ
 * 戻り値: 消費バイト数 (0 = デコード失敗) */
int v86_disasm_one(const u8 *bytes, char *out, int outsz);

#endif /* V86_DISASM_H */
