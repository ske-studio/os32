/*  V86_PIC.H — ゲスト用の仮想 8259A (PIC) ×2                               */
/*                                                                          */
/*  PIC はゲスト専用デバイスではない。OS32 自身が同じチップで 100Hz タイマ   */
/*  とキーボードと rshell のシリアルを回している。素通しにしたらその瞬間に   */
/*  OS32 が死ぬので、ここだけは完全仮想化しかない。                          */
/*                                                                          */
/*  実測 (docs/tasks/v86v2/06_pic_plan.md §1): Ys は                        */
/*                                                                          */
/*      0160:0DF3  OUT 08, 20     OCW2 非特定 EOI                           */
/*      0160:0DF7  OUT 08, 0B     OCW3  ISR を読む指定                      */
/*      0160:0DF9  IN  AL, 08     ISR 読み出し                              */
/*                                                                          */
/*  を回し続ける。読みが常に 0xFF を返すスタブでは ISR が全ビット立って      */
/*  見えるので、EOI を出してももう一度同じ値が返り、永久に抜けられない。     */
/*                                                                          */
/*  ここでやるのはカーネル内の構造体の読み書きだけで、outp() は一切呼ばない。*/
/*  実チップに触れる経路が無いことが OS32 側の安全を保証する。              */
/* ======================================================================== */

#ifndef __V86_PIC_H
#define __V86_PIC_H

#include "types.h"

/* PC-98 の PIC ポート。マスタが 0x00/0x02、スレーブが 0x08/0x0A。 */
#define V86_PIC_M_CMD   0x0000
#define V86_PIC_M_DATA  0x0002
#define V86_PIC_S_CMD   0x0008
#define V86_PIC_S_DATA  0x000A

/* ゲストが ICW2 を書く前に使う既定のベクタベース。
 * PC-98 実機の値で、ゲストは実機の IVT をそのまま引き継いでいるので
 * (04 §3)、これが最も辻褄が合う。IRQ0→INT 08h、IRQ8→INT 10h。 */
#define V86_PIC_M_BASE  0x08
#define V86_PIC_S_BASE  0x10

/* このポートが仮想 PIC のものか */
int  v86_pic_is_port(u16 port);

/* セッション開始時のリセット。全マスク・ISR/IRR クリア・既定ベース。 */
void v86_pic_reset(void);

/* ポートアクセス。v86_io_in/out から振られる。 */
u32  v86_pic_in(u16 port);
void v86_pic_out(u16 port, u32 value);

/* IRQ をゲストに見せてよいか判定する。
 *
 * 見せてよければ注入すべきベクタ (ゲストが ICW2 に書いた base から引く) を
 * *out_vector に入れて 1 を返す。マスクされていれば IRR に立てるだけで 0。
 *
 * **必ずこれを通すこと。** 前回プロジェクトは IMR/ISR を見ずに注入し続けた
 * 結果、ゲストの SP が減り続けて IVT を割り込みフレームで上書きした。 */
int  v86_pic_should_inject(u32 irq, u32 *out_vector);

/* 検証用 */
u32  v86_pic_state(int slave);      /* isr<<16 | irr<<8 | imr */

#endif /* __V86_PIC_H */
