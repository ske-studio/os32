/* ======================================================================== */
/*  V86_DMA.C — V86 DMA (µPD8237A) ch2 仮想化                              */
/*                                                                          */
/*  FDC が DMA ch2 経由でデータ転送するため、DMA コントローラの             */
/*  仮想化が必要。実 DMA には一切アクセスしない。                           */
/*                                                                          */
/*  PC-98 DMA ch2 ポートアドレス:                                           */
/*    0x09: ch2 アドレス (Low/High)                                         */
/*    0x0B: ch2 ワードカウント (Low/High)                                   */
/*    0x15: シングルマスクレジスタ                                          */
/*    0x17: モードレジスタ                                                  */
/*    0x19: フリップフロップクリア                                          */
/*    0x23: ch2 バンクレジスタ                                              */
/*                                                                          */
/*  出典: PC9800Bible §2-9, §1-5                                            */
/* ======================================================================== */

#include "v86_dma.h"
#include "v86_mem.h"

/* ====================================================================== */
/*  仮想 DMA ch2 レジスタ                                                  */
/* ====================================================================== */
static struct {
    u8  flipflop;   /* Low/High 切替フラグ (0=Low次, 1=High次) */
    u16 addr;       /* ch2 ベースアドレス (16bit) */
    u16 count;      /* ch2 ワードカウント */
    u8  bank;       /* ch2 バンクレジスタ (上位8bit) */
    u8  mode;       /* モードレジスタ */
    u8  mask;       /* マスクレジスタ */
} vdma;

/* ====================================================================== */
/*  v86_dma_init — 仮想DMA初期化                                           */
/* ====================================================================== */
void v86_dma_init(void)
{
    vdma.flipflop = 0;
    vdma.addr     = 0;
    vdma.count    = 0;
    vdma.bank     = 0;
    vdma.mode     = 0;
    vdma.mask     = 0xFF; /* 全チャネルマスク (起動直後) */
}

/* ====================================================================== */
/*  v86_dma_io — DMA I/Oポートハンドラ                                    */
/*                                                                          */
/*  戻り値: 1=処理済み, 0=非対象ポート                                     */
/* ====================================================================== */
int v86_dma_io(u16 port, u8 *val, int is_write)
{
    switch (port) {

    /* ---------------------------------------------------------------- */
    /*  0x09: ch2 アドレスレジスタ (Low/High)                           */
    /* ---------------------------------------------------------------- */
    case 0x09:
        if (is_write) {
            if (vdma.flipflop == 0) {
                vdma.addr = (vdma.addr & 0xFF00U) | *val;
                vdma.flipflop = 1;
            } else {
                vdma.addr = (vdma.addr & 0x00FFU) | ((u16)*val << 8);
                vdma.flipflop = 0;
            }
        } else {
            if (vdma.flipflop == 0) {
                *val = (u8)(vdma.addr & 0xFF);
                vdma.flipflop = 1;
            } else {
                *val = (u8)(vdma.addr >> 8);
                vdma.flipflop = 0;
            }
        }
        return 1;

    /* ---------------------------------------------------------------- */
    /*  0x0B: ch2 ワードカウントレジスタ (Low/High)                     */
    /* ---------------------------------------------------------------- */
    case 0x0B:
        if (is_write) {
            if (vdma.flipflop == 0) {
                vdma.count = (vdma.count & 0xFF00U) | *val;
                vdma.flipflop = 1;
            } else {
                vdma.count = (vdma.count & 0x00FFU) | ((u16)*val << 8);
                vdma.flipflop = 0;
            }
        } else {
            if (vdma.flipflop == 0) {
                *val = (u8)(vdma.count & 0xFF);
                vdma.flipflop = 1;
            } else {
                *val = (u8)(vdma.count >> 8);
                vdma.flipflop = 0;
            }
        }
        return 1;

    /* ---------------------------------------------------------------- */
    /*  0x15: シングルマスクレジスタ                                    */
    /* ---------------------------------------------------------------- */
    case 0x15:
        if (is_write) {
            vdma.mask = *val;
        } else {
            *val = vdma.mask;
        }
        return 1;

    /* ---------------------------------------------------------------- */
    /*  0x17: モードレジスタ (書き込みのみ)                             */
    /* ---------------------------------------------------------------- */
    case 0x17:
        if (is_write) {
            vdma.mode = *val;
        } else {
            *val = 0;
        }
        return 1;

    /* ---------------------------------------------------------------- */
    /*  0x19: フリップフロップクリア                                    */
    /* ---------------------------------------------------------------- */
    case 0x19:
        vdma.flipflop = 0;
        *val = 0;
        return 1;

    /* ---------------------------------------------------------------- */
    /*  0x23: ch2 バンクレジスタ                                        */
    /* ---------------------------------------------------------------- */
    case 0x23:
        if (is_write) {
            vdma.bank = *val;
        } else {
            *val = vdma.bank;
        }
        return 1;

    default:
        return 0;
    }
}

/* ====================================================================== */
/*  v86_dma_get_transfer — DMA転送パラメータ取得                          */
/*                                                                          */
/*  DMA ch2 の仮想レジスタから転送先アドレスとバイト数を計算し、            */
/*  V86 メモリ空間内の対応バッファポインタを返す。                          */
/*                                                                          */
/*  DMAアドレスは 24bit: bank(8bit) << 16 | addr(16bit)                    */
/*  V86バッキングRAM (0x300000 ベース) へのアドレス変換は                   */
/*  v86_phys_addr() で行う。bank=0 の場合のみ対応 (V86は1MB以内)。         */
/* ====================================================================== */
u8 *v86_dma_get_transfer(u32 *out_bytes)
{
    u32 linear;
    u16 seg;
    u16 off;

    /* カウント+1 がバイト数 (DMA は count-1 を格納する慣例) */
    *out_bytes = (u32)vdma.count + 1;

    /* 24bitアドレス: bank << 16 | addr */
    linear = ((u32)vdma.bank << 16) | vdma.addr;
    linear &= 0xFFFFFUL; /* 1MB境界でクリップ */

    /* seg:off に分解して v86_phys_addr() でバッキングRAMを参照 */
    seg = (u16)(linear >> 4);
    off = (u16)(linear & 0x0F);

    return v86_phys_addr(seg, off);
}
